/** 급수 합. τ는 J2000부터의 천년 단위 율리우스 세기. */
function series(table: readonly (readonly Term[])[], tau: number): number {
  let total = 0;
  for (let i = table.length - 1; i >= 0; i--) {
    let sum = 0;
    for (const [a, b, c] of table[i]) sum += a * Math.cos(b + c * tau);
    total = total * tau + sum;
  }
  return total / 1e8;
}

/** 율리우스적일(TT) → J2000 기준 율리우스 세기 */
export function centuriesSinceJ2000(jde: number): number {
  return (jde - 2451545.0) / 36525;
}

/**
 * 장동(황경). Meeus Ch.22 약식 — 정확도 약 0.5초각(시간으로 12초).
 * 절기 판정 허용 오차(2.5초각) 안에 충분히 들어온다.
 */
export function nutationInLongitude(t: number): number {
  const omega = (125.04452 - 1934.136261 * t) * RAD;
  const l = (280.4665 + 36000.7698 * t) * RAD;
  const lp = (218.3165 + 481267.8813 * t) * RAD;
  const arcsec =
    -17.2 * Math.sin(omega) -
    1.32 * Math.sin(2 * l) -
    0.23 * Math.sin(2 * lp) +
    0.21 * Math.sin(2 * omega);
  return arcsec / 3600;
}

/**
 * 태양의 겉보기 황경 (도, 0~360).
 * @param jde 율리우스적일 (TT 기준)
 */
export function apparentSolarLongitude(jde: number): number {
  const t = centuriesSinceJ2000(jde);
  const tau = t / 10;

  // 지구에서 본 태양 = 태양에서 본 지구 + 180도
  const earthL = (series(EARTH_L, tau) / RAD) % 360;
  const radius = series(EARTH_R, tau);
  let lon = earthL + 180;

  // VSOP87(동역학 기준계) → FK5. 황경 보정은 상수항뿐이다
  // (0.03916 항은 황위에만 적용된다 — 여기서는 황경만 쓴다).
  lon -= 0.09033 / 3600;

  // 장동 + 광행차. 광행차는 태양까지의 거리에 반비례한다.
  lon += nutationInLongitude(t);
  lon -= 20.4898 / 3600 / radius;

  return ((lon % 360) + 360) % 360;
}

/**
 * ΔT = TT − UT (초). Espenak & Meeus 다항식.
 * 1900년대 초 약 −3초, 2020년대 약 +70초. 분 단위 정확도에서 무시할 수 없다.
 * 2050년 이후는 외삽이라 미래 절기는 초 단위 오차가 커질 수 있다.
 */
export function deltaT(year: number, month: number): number {
  const y = year + (month - 0.5) / 12;

  if (y < 1920) {
    const t = y - 1900;
    return (
      -2.79 + 1.494119 * t - 0.0598939 * t * t + 0.0061966 * t ** 3 - 0.000197 * t ** 4
    );
  }
  if (y < 1941) {
    const t = y - 1920;
    return 21.2 + 0.84493 * t - 0.0761 * t * t + 0.0020936 * t ** 3;
  }
  if (y < 1961) {
    const t = y - 1950;
    return 29.07 + 0.407 * t - t * t / 233 + t ** 3 / 2547;
  }
  if (y < 1986) {
    const t = y - 1975;
    return 45.45 + 1.067 * t - t * t / 260 - t ** 3 / 718;
  }
  if (y < 2005) {
    const t = y - 2000;
    return (
      63.86 + 0.3345 * t - 0.060374 * t * t + 0.0017275 * t ** 3 +
      0.000651814 * t ** 4 + 0.00002373599 * t ** 5
    );
  }
  if (y < 2050) {
    const t = y - 2000;
    return 62.92 + 0.32217 * t + 0.005589 * t * t;
  }
  if (y < 2150) {
    const u = (y - 1820) / 100;
    return -20 + 32 * u * u - 0.5628 * (2150 - y);
  }
  const u = (y - 1820) / 100;
  return -20 + 32 * u * u;
}

/** 그레고리력 날짜(UT) → 율리우스적일. 시각은 하루의 소수로 받는다. */
export function julianDayUt(year: number, month: number, dayFraction: number): number {
  let y = year;
  let m = month;
  if (m <= 2) {
    y -= 1;
    m += 12;
  }
  const a = Math.floor(y / 100);
  const b = 2 - a + Math.floor(a / 4);
  return (
    Math.floor(365.25 * (y + 4716)) +
    Math.floor(30.6001 * (m + 1)) +
    dayFraction +
    b -
    1524.5
  );
}

/** 율리우스적일 → 그레고리력 날짜 + 하루의 소수 */
export function fromJulianDay(jd: number): {
  year: number;
  month: number;
  day: number;
  dayFraction: number;
} {
  const z = Math.floor(jd + 0.5);
  const f = jd + 0.5 - z;
  const alpha = Math.floor((z - 1867216.25) / 36524.25);
  const a = z < 2299161 ? z : z + 1 + alpha - Math.floor(alpha / 4);
  const b = a + 1524;
  const c = Math.floor((b - 122.1) / 365.25);
  const d = Math.floor(365.25 * c);
  const e = Math.floor((b - d) / 30.6001);

  const day = b - d - Math.floor(30.6001 * e);
  const month = e < 14 ? e - 1 : e - 13;
  const year = month > 2 ? c - 4716 : c - 4715;

  return { year, month, day, dayFraction: f };
}
