/**
 * 태양의 겉보기 황경(apparent longitude). 절기는 이 값이 15도의 배수를 지나는
 * 순간이므로, 절기 정확도는 전적으로 여기서 결정된다.
 *
 * 출처: Jean Meeus, *Astronomical Algorithms* 2nd ed.
 *   Ch.32  VSOP87 지구 헬리오센트릭 황경·동경 (절단 급수)
 *   Ch.22  장동(nutation) 약식
 *   Ch.25  FK5 보정, 광행차
 *   ΔT     Espenak & Meeus 다항식 (NASA 일식 카탈로그)
 *
 * 정확도 목표는 분 단위다. 태양 황경 1초각 ≈ 시간 24초이므로 2.5초각 안에
 * 들어와야 한다. 아래 절단으로 1초각 수준이 나온다.
 *
 * ΔT를 빼먹으면 안 된다. 2020년대 기준 약 70초라 그것만으로 1분 이상 틀린다.
 *
 *   벽시계(KST) ──UT──▶ ΔT 보정 ──TT──▶ VSOP87 ──▶ 황경 λ
 *                                                    │
 *                                    장동 Δψ + 광행차 ┘
 */

